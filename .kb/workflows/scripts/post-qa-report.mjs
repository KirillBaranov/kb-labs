#!/usr/bin/env node
// Step: Post Adversarial QA Report to PR
// Env: ISSUE_NUMBER, OWNER, REPO, PR_NUMBER, QA_VERDICT, QA_REPORT
import { readFileOrEmpty, ghComment } from './lib/kb.mjs';

const { ISSUE_NUMBER, OWNER, REPO, PR_NUMBER, QA_VERDICT, QA_REPORT } = process.env;
const REPO_FULL = `${OWNER}/${REPO}`;

const report = QA_REPORT || readFileOrEmpty(`/tmp/kb-qa-report-${ISSUE_NUMBER}.md`) || 'Report not available';
const icon = QA_VERDICT === 'BUGS_FOUND' ? '🐛' : '✅';

const body = `## ${icon} Adversarial QA Report\n\n**Verdict:** ${QA_VERDICT}\n\n${report}\n\n---\n*Generated by KB Labs Adversarial QA Agent*`;
ghComment({ number: PR_NUMBER, repoFull: REPO_FULL, body });
