#!/usr/bin/env node
// Step: Post full pipeline timeline to PR — the complete work history
// Env: PR_NUMBER, OWNER, REPO, ISSUE_NUMBER, ISSUE_TITLE,
//      REVIEW_PASSED, REVIEW_ISSUES_COUNT, ARCHITECT_VERDICT, ARCHITECT_BLOCKERS_COUNT,
//      QA_VERDICT, QA_BUGS_COUNT, VERIFY_VERDICT, VERIFY_CRITERIA_PASSED, VERIFY_CRITERIA_TOTAL
import { ghComment } from './lib/kb.mjs';

const {
  PR_NUMBER, OWNER, REPO, ISSUE_NUMBER, ISSUE_TITLE,
  REVIEW_PASSED, REVIEW_ISSUES_COUNT,
  ARCHITECT_VERDICT, ARCHITECT_BLOCKERS_COUNT,
  QA_VERDICT, QA_BUGS_COUNT,
  VERIFY_VERDICT, VERIFY_CRITERIA_PASSED, VERIFY_CRITERIA_TOTAL,
} = process.env;
const REPO_FULL = `${OWNER}/${REPO}`;

const reviewLine = REVIEW_PASSED === 'true'
  ? '✅ **Code Review** — passed (0 issues)'
  : `✅ **Code Review** — ${REVIEW_ISSUES_COUNT} issue(s) found → agent fixed → re-run passed`;

const architectLine = (ARCHITECT_VERDICT === 'APPROVED' || !ARCHITECT_VERDICT)
  ? '✅ **Architect Review** — approved'
  : `✅ **Architect Review** — ${ARCHITECT_BLOCKERS_COUNT} blocker(s) found → agent fixed → re-run approved`;

const qaLine = (QA_VERDICT === 'PASSED' || !QA_VERDICT)
  ? '✅ **Adversarial QA** — passed (0 bugs)'
  : `✅ **Adversarial QA** — ${QA_BUGS_COUNT} bug(s) found → agent fixed → re-run passed`;

const verifyPassed = VERIFY_VERDICT === 'PASSED';
const verifyPhase = verifyPassed ? '✅' : `❌ Failed (${VERIFY_CRITERIA_PASSED || '?'}/${VERIFY_CRITERIA_TOTAL || '?'} criteria)`;
const verifyLine = verifyPassed
  ? `✅ **Functional Verification** — ${VERIFY_CRITERIA_PASSED}/${VERIFY_CRITERIA_TOTAL} acceptance criteria passed`
  : `❌ **Functional Verification** — ${VERIFY_CRITERIA_PASSED || '?'}/${VERIFY_CRITERIA_TOTAL || '?'} acceptance criteria passed`;

const body = `## 📋 Pipeline Timeline — Issue #${ISSUE_NUMBER}

**${ISSUE_TITLE}**

### Phases completed

| # | Phase | Result |
|---|-------|--------|
| 1 | Planning & Approval | ✅ Plan approved |
| 2 | Implementation | ✅ Implemented + self-verified |
| 3 | Code Review | ✅ |
| 4 | Architect Review | ✅ |
| 5 | Adversarial QA | ✅ |
| 6 | Functional Verification | ${verifyPhase} |
| 7 | Static Gates (type-check + tests) | ✅ |
| 8 | CI | ✅ Green |

### Audit history

${reviewLine}
${architectLine}
${qaLine}
${verifyLine}

### Artifacts
See individual PR comments above for full reports from each phase.

---
*Generated by task-to-pr autonomous pipeline*`;

ghComment({ number: PR_NUMBER, repoFull: REPO_FULL, body });
