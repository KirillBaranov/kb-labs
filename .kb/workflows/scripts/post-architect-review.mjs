#!/usr/bin/env node
// Step: Post Architect Review to PR
// Env: ISSUE_NUMBER, OWNER, REPO, PR_NUMBER, ARCHITECT_VERDICT, ARCHITECT_REVIEW
import { readFileOrEmpty, ghComment } from './lib/kb.mjs';

const { ISSUE_NUMBER, OWNER, REPO, PR_NUMBER, ARCHITECT_VERDICT, ARCHITECT_REVIEW } = process.env;
const REPO_FULL = `${OWNER}/${REPO}`;

const review = ARCHITECT_REVIEW || readFileOrEmpty(`/tmp/kb-architect-review-${ISSUE_NUMBER}.md`) || 'Review not available';
const icon = ARCHITECT_VERDICT === 'NEEDS_FIXES' ? '⚠️' : '✅';

const body = `## ${icon} Architect Review\n\n${review}\n\n---\n*Generated by KB Labs Architect Agent*`;
ghComment({ number: PR_NUMBER, repoFull: REPO_FULL, body });
